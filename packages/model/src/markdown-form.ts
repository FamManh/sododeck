import type { ProblemEntry } from './report-json';

const BEGIN = '%% sododeck:begin';
const BEGIN_LINE = `${BEGIN} — generated by Sododeck; edit titles and notes, not the marker comments %%`;
const END_LINE = '%% sododeck:end %%';
const DATA_OPEN = '%% sododeck:data';
const UNNAMED = '(unnamed)';

export { isDeckMarkdown, MARKER_KEY, MARKER_VALUE };

export type FromMarkdown =
  { ok: true; deckText: string; edited: boolean } | { ok: false; entries: ProblemEntry[] };

