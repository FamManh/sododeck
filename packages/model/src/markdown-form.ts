function failure(code: MdProblemCode): FromMarkdown {
  const problem = MD_PROBLEMS[code];
  return {
    ok: false,
    entries: [{ code, severity: 'error', message: problem.message, fix: problem.fix }],
  };
}

const canonicalText = (value: unknown): string =>
  `${JSON.stringify(canonicalize(value), null, 2)}\n`;

/** The canonical text of an empty deck: what a marker-only note or an empty file opens as. */
export const emptyDeckText = (): string => canonicalText(emptySododeckFile());

function bodyTargets(deck: Json): Map<string, Target[]> {
  const byId = new Map<string, Target[]>();
  const add = (target: Target): void => {
    byId.set(target.id, [...(byId.get(target.id) ?? []), target]);
    target.children.forEach(add);
  };
  add({ id: 'deck', kind: KIND.deck, object: deck, children: [] });
  for (const { targets } of sectionsOf(deck)) targets.forEach(add);
  return byId;
}

/**
 * Read a `.sododeck.md` note back to deck JSON. Lenient about everything except the deck block: it
 * never validates the deck (the editor and `inspectDeckText` do). `edited` is true when at least
 * one title, notes value or picture link in the readable part differs from the block.
 */
export function fromMarkdown(markdown: string): FromMarkdown {
  const text = markdown.startsWith('\uFEFF') ? markdown.slice(1) : markdown;
  if (!isDeckMarkdown(text)) return failure('md-no-marker');
  const { region } = splitFile(text);
  if (region === null)
    return { ok: true, deckText: canonicalText(emptySododeckFile()), edited: false };

  const units = parseRegion(region);
  const blocks = units.filter((u) => u.kind === 'data');
  if (blocks.length === 0) return failure('md-no-deck-block');
  if (blocks.length > 1) return failure('md-two-deck-blocks');
  const block = blocks[0];
  let deck: unknown;
  try {
    deck = block?.kind === 'data' && block.text !== null ? JSON.parse(block.text) : undefined;
  } catch {
    return failure('md-deck-block-not-json');
  }
  if (!isRecord(deck)) return failure('md-deck-block-not-json');

  const edited = applyReadable(deck, units);
  return { ok: true, deckText: canonicalText(deck), edited };
}

/** Applies title, prose and picture-link edits by id; returns whether any value changed. */
function applyReadable(deck: Json, units: readonly Unit[]): boolean {
  const targets = bodyTargets(deck);
  const used = new Map<string, number>();
  const take = (id: string): Target | undefined => {
    const list = targets.get(id);
    if (list === undefined) return undefined;
    const n = used.get(id) ?? 0;
    return list[Math.min(n, list.length - 1)];
  };
  // Duplicate ids (rare) are matched in writing order: the nth heading with an id is its nth target.
  const advance = (id: string): void => {
    used.set(id, (used.get(id) ?? 0) + 1);
  };
  let edited = false;
  const seenBody = new Set<string>();

  for (const unit of units) {
    if (unit.kind === 'heading' && unit.id !== null) {
      const target = take(unit.id);
      advance(unit.id);
      if (target === undefined) continue;
      seenBody.clear();
      const field = target.kind.title;
      if (field === null) continue;
      const value = decodeTitle(unit.text);
      const current = typeof target.object[field] === 'string' ? target.object[field] : '';
      if (value === '') continue;
      const settled =
        current.trim() === '' && target.kind.title !== null ? UNNAMED : settledTitle(current);
      if (value === settled) continue;
      target.object[field] = value;
      edited = true;
    } else if (unit.kind === 'body') {
      // The body belongs to the target of the most recent heading with this id.
      const list = targets.get(unit.id);
      if (list === undefined) continue;
      const n = Math.max(0, (used.get(unit.id) ?? 1) - 1);
      const target = list[Math.min(n, list.length - 1)];
      const spec = target?.kind.bodies.find((b) => b.field === unit.field);
      if (target === undefined || spec === undefined) continue;
      const key = `${unit.id}:${unit.field}:${String(n)}`;
      if (seenBody.has(key)) continue;
      seenBody.add(key);
      const value = decodeBody(unit.lines);
      const current = target.object[spec.field];
      const was = typeof current === 'string' ? current : undefined;
      if (value === (was === undefined ? '' : settledBody(was))) continue;
      if (value === '') {
        if (spec.required === true) continue;
        Reflect.deleteProperty(target.object, spec.field);
      } else {
        target.object[spec.field] = value;
      }
      edited = true;
    } else if (unit.kind === 'picture' && unit.link !== null) {
      const assets = isRecord(deck.assets) ? deck.assets : {};
      const asset = assets[unit.id];
      if (!isRecord(asset) || typeof asset.path !== 'string') continue;
      const link = unit.link.replace(/[|#].*$/, '').trim();
      if (link === '' || link === asset.path || checkPicturePath(link) !== null) continue;
      asset.path = link;
      edited = true;
    }
  }
  return edited;
}
