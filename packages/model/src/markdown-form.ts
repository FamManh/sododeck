/**
 * The `.sododeck.md` form of a deck (070, contract `specs/070-obsidian-plugin/contracts/
 * markdown-form.md`, ADR 0051): the same canonical deck JSON wrapped in a Markdown note, with the
 * deck's titles and prose mirrored as readable text so a notes app can search and link them, and
 * edits to that text read back by stable id. Text in, text out: no Yjs, no I/O, and no Markdown
 * parser (a small line grammar we own, so text outside the owned region is copied byte for byte).
 */
